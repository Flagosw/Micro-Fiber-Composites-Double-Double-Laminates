function [results,summary,benchmarks,angleRows,frontRows,modeComparison] = mfc_extensions(results)
%MFC_EXTENSIONS Reproduce anisotropy, summed Pareto and Hessian analyses.
names={'d33','d31'};benchmarks=struct([]);angleRows=table;
for j=1:2
    name=names{j};z=results.(name);model=z.model;reference=z.reference;r=z.atlas;
    phi=r.phi;psi=r.psi;
    [ae,ee]=mfc_ratio(r.Ex,r.Ey);[ag,eg]=mfc_ratio(r.G(:,:,1),r.G(:,:,2));
    [ast,es]=mfc_ratio(r.eps(:,:,1),r.eps(:,:,2));
    esum=r.Ex+r.Ey;gsum=sum(abs(r.G(:,:,1:2)),3);strainSum=sum(abs(r.eps(:,:,1:2)),3);
    [front,frontcheck]=mfc_pareto(cat(3,esum,gsum,strainSum));
    hc=mfc_hessian(model,reference,phi,psi,.1);hf=mfc_hessian(model,reference,phi,psi,.05);
    avg=(hf(:,:,1,1)+hf(:,:,2,2))/2;rad=hypot((hf(:,:,1,1)-hf(:,:,2,2))/2,hf(:,:,1,2));
    eigen=cat(3,avg-rad,avg+rad);rho=max(abs(eigen),[],3);
    herror=max(abs(hf-hc),[],'all')/max(abs(hf),[],'all');assert(herror<1e-4);
    hopt=squeeze(mfc_hessian(model,reference,45,45,.01));
    hopt2=squeeze(mfc_hessian(model,reference,45,45,.005));
    perturbed=mfc_score(mfc_evaluate(model,45.01,45.01),reference);
    direction=[.01;.01];actual=z.dd45.M-perturbed.M;quadratic=-.5*direction.'*hopt*direction;
    assert(abs(actual-quadratic)/actual<1e-4);
    signedSum=r.G(:,:,1)+r.G(:,:,2);
    s=struct('A_E',rangeOf(ae,phi,psi),'A_G',rangeOf(ag,phi,psi), ...
        'A_epsilon',rangeOf(ast,phi,psi),'ratio_guards',struct('A_E',ee,'A_G',eg,'A_epsilon',es), ...
        'E_sum_Pa',rangeOf(esum,phi,psi),'G_abs_sum_C_per_m',rangeOf(gsum,phi,psi), ...
        'strain_abs_sum',rangeOf(strainSum,phi,psi), ...
        'G_signed_sum_C_per_m',[min(signedSum,[],'all') max(signedSum,[],'all')], ...
        'G_abs_sum_relative_span',(max(gsum,[],'all')-min(gsum,[],'all'))/mean(gsum,'all'), ...
        'G_abs_sum_fraction_equal_to_signed_sum',mean(abs(gsum-abs(signedSum(1,1)))<=1e-10*abs(signedSum(1,1)),'all'), ...
        'three_objective_pareto',frontcheck,'curvature_spectral_radius_per_deg2',rangeOf(rho,phi,psi), ...
        'hessian_step_deg',.05,'hessian_coarse_step_deg',.1,'hessian_coarse_fine_scaled_error',herror, ...
        'H_M_at_45_per_deg2',hopt,'H_M_at_45_half_step_per_deg2',hopt2, ...
        'H_M_at_45_eigenvalues_per_deg2',eig(hopt), ...
        'small_error_check',struct('angle_error_deg',direction,'actual_M_loss',actual, ...
        'quadratic_predicted_M_loss',quadratic,'relative_difference',abs(actual-quadratic)/actual));
    summary.(name)=s;
    ext=struct('phi',phi,'psi',psi,'A_E',ae,'A_G',ag,'A_epsilon',ast, ...
        'E_sum',esum,'G_abs_sum',gsum,'strain_abs_sum',strainSum,'pareto3',front, ...
        'H_M',hf,'H_M_eigenvalues',eigen,'H_M_spectral_radius',rho);
    results.(name).extensions=ext;
    arch={'UDx','UDy','cross_ply','QI','DD45','DD0_45','DD45_90'};
    angles=[0 0;90 90;0 90;22.5 67.5;45 45;0 45;45 90];
    for k=1:numel(arch)
        v=mfc_score(mfc_evaluate(model,angles(k,1),angles(k,2)),reference);
        row=struct('mode',name,'architecture',arch{k},'Phi_deg',angles(k,1),'Psi_deg',angles(k,2), ...
            'Ex_GPa',v.Ex/1e9,'Ey_GPa',v.Ey/1e9,'absGx_C_per_m',abs(v.G(1)), ...
            'absGy_C_per_m',abs(v.G(2)),'epsx_microstrain',v.eps(1)*1e6,'epsy_microstrain',v.eps(2)*1e6, ...
            'E_sum_GPa',(v.Ex+v.Ey)/1e9,'G_abs_sum_C_per_m',sum(abs(v.G(1:2))), ...
            'strain_abs_sum_microstrain',sum(abs(v.eps(1:2)))*1e6, ...
            'A_E',v.Ex/v.Ey,'A_G',abs(v.G(1)/v.G(2)),'A_epsilon',abs(v.eps(1)/v.eps(2)),'M',v.M);
        benchmarks=[benchmarks;row]; %#ok<AGROW>
    end
    n=numel(phi);row=table(repmat(string(name),n,1),flat(phi),flat(psi),flat(r.Ex)/1e9, ...
        abs(flat(r.G(:,:,1))),flat(r.M),flat(r.pareto),flat(esum)/1e9,flat(gsum),flat(strainSum)*1e6,flat(front), ...
        'VariableNames',{'mode','Phi_deg','Psi_deg','Ex_GPa','absGx_C_per_m','M', ...
        'nondominated_Ex_absGx','E_sum_GPa','G_abs_sum_C_per_m','strain_abs_sum_microstrain','nondominated_three_sum_objectives'});
    angleRows=[angleRows;row]; %#ok<AGROW>
    fprintf('%s: summed Pareto %d angles; Hessian step error %.3g\n',name,nnz(front),herror);
end
a=results.d33.atlas;b=results.d31.atlas;
[rg,gg]=mfc_ratio(a.G(:,:,1),b.G(:,:,1));[re,eg]=mfc_ratio(a.eps(:,:,1),b.eps(:,:,1));
modeComparison=struct('phi',a.phi,'psi',a.psi,'R_G',rg,'R_epsilon',re);
summary.mode_comparison=struct('definition','x-direction magnitudes; same 400 V, mode-specific field length', ...
    'R_G',rangeOf(rg,a.phi,a.psi),'R_epsilon',rangeOf(re,a.phi,a.psi), ...
    'ratio_guards',struct('R_G',gg,'R_epsilon',eg));
frontRows=angleRows(angleRows.nondominated_three_sum_objectives,:);
end

function out=rangeOf(value,phi,psi)
% Row-major tie order is retained for Python comparisons; ties are not unique optima.
v=flat(value);p=flat(phi);s=flat(psi);[lo,i]=min(v);[hi,j]=max(v);
out=struct('min',lo,'max',hi,'min_phi_psi_deg',[p(i) s(i)],'max_phi_psi_deg',[p(j) s(j)]);
end
function value=flat(value)
value=reshape(value.',[],1);
end
